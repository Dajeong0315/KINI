-- N1: public catalog and recipe/nutrition reads. No private/demo seed.
ALTER TABLE ingredients ADD COLUMN source_type TEXT NOT NULL DEFAULT 'unknown';
ALTER TABLE ingredients ADD COLUMN data_confidence DOUBLE PRECISION;
ALTER TABLE ingredients ADD COLUMN is_composite INTEGER NOT NULL DEFAULT 0;
ALTER TABLE ingredients ADD COLUMN requires_label_check INTEGER NOT NULL DEFAULT 0;
CREATE TABLE recipes(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, servings DOUBLE PRECISION, cook_time_minutes INTEGER, spicy INTEGER NOT NULL DEFAULT 0);
CREATE TABLE recipe_ingredients(recipe_id BIGINT NOT NULL REFERENCES recipes(id), ingredient_id BIGINT NOT NULL REFERENCES ingredients(id), quantity_g DOUBLE PRECISION, PRIMARY KEY(recipe_id,ingredient_id));
CREATE TABLE ingredient_nutrition(ingredient_id BIGINT PRIMARY KEY REFERENCES ingredients(id), energy_kcal DOUBLE PRECISION, protein_g DOUBLE PRECISION, carbohydrate_g DOUBLE PRECISION, fat_g DOUBLE PRECISION, sodium_mg DOUBLE PRECISION, basis_amount_g DOUBLE PRECISION, source_type TEXT NOT NULL DEFAULT 'unknown', source_reference TEXT, verified_at TEXT, confidence DOUBLE PRECISION);
CREATE TABLE catalog_data_sources (
    code TEXT PRIMARY KEY, name TEXT NOT NULL, documentation_url TEXT NOT NULL,
    rights_status TEXT NOT NULL CHECK(rights_status IN ('review_required','approved'))
);
