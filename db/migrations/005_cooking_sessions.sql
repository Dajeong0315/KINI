-- Validated cooking drafts only. Completion/intake writes remain disabled.
CREATE TABLE cooking_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL REFERENCES households(id),
    meal_session_id BIGINT NOT NULL REFERENCES meal_sessions(id),
    request_id BIGINT NOT NULL REFERENCES recommendation_requests(id),
    recipe_id BIGINT NOT NULL REFERENCES recipes(id),
    ingredients_json TEXT NOT NULL CHECK (jsonb_typeof(ingredients_json::jsonb) = 'array'),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed')),
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    completed_at TEXT,
    meal_record_id BIGINT REFERENCES meal_records(id),
    planned_servings INTEGER NOT NULL CHECK (planned_servings > 0)
);
CREATE INDEX cooking_household_sessions ON cooking_sessions(household_id,id);
REVOKE ALL ON cooking_sessions FROM PUBLIC;
